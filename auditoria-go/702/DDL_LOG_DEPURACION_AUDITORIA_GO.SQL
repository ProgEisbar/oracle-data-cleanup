--------------------------------------------------------------------------------
-- DDL_LOG_DEPURACION_AUDITORIA_GO.SQL
--
-- Tabla de logueo independiente para el proceso AUDITORIA_GO.
--
-- IMPORTANTE:
--   - En ENTIDAD se crea solo la tabla.
--   - En HISTORICO se crea la tabla y la secuencia.
--   - El PROCESS_ID se genera en HISTORICO y se informa a ENTIDAD.
--------------------------------------------------------------------------------

--------------------------------------------------------------------------------
-- ENTIDAD
--------------------------------------------------------------------------------

CREATE TABLE SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO
(
  PROCESS_ID       NUMBER,
  DATE_TIME        DATE,
  EXECUTION_TIME   VARCHAR2(30 CHAR),
  CLEANING_DATE    DATE,
  ENTITY           VARCHAR2(20 CHAR),
  MESSAGE          VARCHAR2(300 CHAR),
  SP_NAME          VARCHAR2(100 BYTE),
  ERROR_CODE       VARCHAR2(15 BYTE),
  ERROR_BACKTRACE  VARCHAR2(300 CHAR),
  STACK_ERROR      VARCHAR2(300 CHAR)
)
TABLESPACE USERS
PCTFREE    10
INITRANS   1
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           )
NOLOGGING
NOCOMPRESS
NOCACHE;

COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.PROCESS_ID IS 'ID del proceso';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.DATE_TIME IS 'Fecha de ejecucion';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.EXECUTION_TIME IS 'Tiempo de ejecucion';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.CLEANING_DATE IS 'Fecha de depuracion';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.ENTITY IS 'Entidad';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.MESSAGE IS 'Mensaje';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.SP_NAME IS 'Nombre Del Stored Procedure';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.ERROR_CODE IS 'Codigo de Error';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.ERROR_BACKTRACE IS 'Backtrace Error';
COMMENT ON COLUMN SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO.STACK_ERROR IS 'Stack Error';

GRANT SELECT ON SOPORTEDBA.LOG_DEPURACION_AUDITORIA_GO TO MONITOREO;

